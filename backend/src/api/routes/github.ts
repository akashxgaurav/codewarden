import { Router, type Request } from "express";
import { HttpError } from "../../lib/errors.js";
import { githubConfig, isGithubAppConfigured } from "../../config/env.js";
import {
  addPullRequestComment,
  applyInstallationWebhook,
  applyRepositoryWebhook,
  createPullRequest,
  getInstallation,
  handleGenericWebhook,
  installationUrl,
  linkRepo,
  listInstallationRepos,
  listInstallations,
  verifyWebhook,
} from "../../services/github-app.service.js";
import { activity } from "../../services/activity.service.js";
import { patchWorkspace } from "../../services/firebase.service.js";
import type { GitHubInstallation } from "../../types/index.js";

export const githubRouter = Router();

function installationIdFrom(value: unknown): number | undefined {
  const id = Number(value);
  return Number.isInteger(id) && id > 0 ? id : undefined;
}

function ownerFrom(req: Request): string | null {
  const bodyOwner = req.body && typeof req.body === "object" ? (req.body as { ownerUid?: unknown }).ownerUid : null;
  return req.user?.uid ?? (typeof bodyOwner === "string" ? bodyOwner : null);
}

githubRouter.get("/config", (req, res) => {
  const configured = isGithubAppConfigured();
  const state = typeof req.query.state === "string" ? req.query.state : undefined;
  res.json({
    ok: true,
    configured,
    appId: configured ? githubConfig.appId : "",
    slug: configured ? githubConfig.slug : "",
    installationUrl: configured ? installationUrl(undefined, state) : null,
    webhookConfigured: Boolean(githubConfig.webhookSecret),
  });
});

githubRouter.get("/installations", async (_req, res) => {
  if (!isGithubAppConfigured()) throw new HttpError(503, "GitHub App is not configured.");
  res.json({ ok: true, installations: await listInstallations() });
});

githubRouter.get("/repositories", async (req, res) => {
  const id = installationIdFrom(req.query.installationId);
  if (!id) throw new HttpError(400, "installationId is required");
  await getInstallation(id);
  res.json({ ok: true, repositories: await listInstallationRepos(id) });
});

githubRouter.post("/link", async (req, res) => {
  const body = req.body ?? {};
  const ownerUid = ownerFrom(req);
  const { workspaceId, owner, repo } = body;
  const installationId = installationIdFrom(body.installationId);
  if (!ownerUid) throw new HttpError(401, "Sign in to connect a GitHub installation.");
  if (!workspaceId || typeof owner !== "string" || typeof repo !== "string" || !installationId) {
    throw new HttpError(400, "workspaceId, owner, repo and installationId are required");
  }

  const installation = await getInstallation(installationId);
  linkRepo({ owner, repo, workspaceId, installationId, ownerUid });
  const github: GitHubInstallation = {
    installationId,
    account: installation.account?.login ?? owner,
    accountType: installation.account?.type === "Organization" ? "Organization" : "User",
    suspended: Boolean(installation.suspended_at),
    repositorySelection: installation.repository_selection === "selected" ? "selected" : "all",
    htmlUrl: installation.html_url ?? "",
    connectedAt: new Date().toISOString(),
  };
  await patchWorkspace(ownerUid, workspaceId, { github });
  activity.publish({
    level: "success",
    category: "github",
    message: `GitHub App connected to ${owner}/${repo}`,
    ownerUid,
    workspaceId,
    details: { installationId },
  });
  res.json({ ok: true, github });
});

githubRouter.post("/pull-request", async (req, res) => {
  const body = req.body ?? {};
  const ownerUid = ownerFrom(req);
  const installationId = installationIdFrom(body.installationId);
  if (!ownerUid) throw new HttpError(401, "Sign in to create a pull request.");
  for (const key of ["owner", "repo", "head", "base", "title"] as const) {
    if (typeof body[key] !== "string" || !body[key]) throw new HttpError(400, `${key} is required`);
  }
  if (!installationId) throw new HttpError(400, "installationId is required");

  const pr = await createPullRequest({
    owner: body.owner,
    repo: body.repo,
    installationId,
    head: body.head,
    base: body.base,
    title: body.title,
    body: typeof body.body === "string" ? body.body : "Generated by Codewarden 2.",
  });
  if (typeof body.comment === "string" && body.comment) {
    await addPullRequestComment(body.owner, body.repo, installationId, pr.number, body.comment);
  }
  activity.publish({
    level: "success",
    category: "github",
    message: `Pull request #${pr.number} opened in ${body.owner}/${body.repo}`,
    ownerUid,
    workspaceId: typeof body.workspaceId === "string" ? body.workspaceId : undefined,
    details: pr,
  });
  res.json({ ok: true, ...pr });
});

githubRouter.post("/webhook", async (req, res) => {
  const signature = req.get("x-hub-signature-256") ?? undefined;
  const raw = Buffer.isBuffer(req.body) ? req.body : Buffer.from(JSON.stringify(req.body ?? {}));
  if (!verifyWebhook(raw, signature)) {
    activity.publish({
      level: "warning",
      category: "github-webhook",
      message: "Rejected a GitHub webhook with an invalid signature",
    });
    throw new HttpError(401, "Invalid webhook signature");
  }

  const event = req.get("x-github-event") ?? "unknown";
  const payload = (() => {
    try {
      return JSON.parse(raw.toString("utf8")) as Record<string, unknown>;
    } catch {
      return {};
    }
  })();

  if (event === "installation") {
    await applyInstallationWebhook(String(payload.action ?? ""), payload);
  } else if (event === "installation_repositories") {
    await applyRepositoryWebhook(String(payload.action ?? ""), payload);
  } else {
    handleGenericWebhook(event, payload);
  }

  res.json({ ok: true, event });
});
