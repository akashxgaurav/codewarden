/**
 * Shared domain types.
 *
 * The Incident and Workspace shapes are produced by the Codewarden API
 * (backend/src/api/analysis.service.js) and stored in the Firebase Realtime
 * Database, so they are kept deliberately flat and serialisable.
 */

export type IncidentStatus =
  | "pending"
  | "running"
  | "fixed"
  | "not_fixable"
  | "validation_failed"
  | "no_diagnosis"
  | "failed";

export type Confidence = "high" | "medium" | "low";

export type IncidentSource = "MANUAL" | "CLOUDWATCH";

export type IncidentSeverity = "CRITICAL" | "HIGH" | "MEDIUM" | "LOW" | "INFO" | "UNKNOWN";

export interface RegressionTest {
  path: string | null;
  description: string | null;
}

/**
 * The CloudWatch connection of a workspace.
 *
 * It describes the log group the subscription filter reads. The template that
 * creates the filter is generated by the API, because it carries the ingest
 * key of the workspace.
 */
export interface CloudWatchConnection {
  /** The region the log group lives in, for example eu-west-1. */
  region: string;
  /** The name of the log group, for example /aws/lambda/payments. */
  logGroupName: string;
  /** The subscription filter pattern that selects the errors. */
  filterPattern: string;
  /** True once the customer created the CloudFormation stack. */
  connected: boolean;
  /** When the stack was created, so the dashboard can show it. */
  connectedAt: number | null;
}

/** A GitHub App installation stored on a workspace. */
export interface GitHubConnection {
  installationId: number;
  account: string;
  accountType: "Organization" | "User";
  suspended: boolean;
  repositorySelection: "all" | "selected";
  htmlUrl: string;
  connectedAt: string | number;
}

export interface GitHubInstallation {
  id: number;
  account: { login: string; type: string; html_url: string };
  repository_selection: "all" | "selected";
  suspended_at: string | null;
  html_url: string;
}

export interface GithubRepository {
  id: number;
  name: string;
  full_name: string;
  private: boolean;
  default_branch: string;
  html_url: string;
  archived: boolean;
  permissions?: { push?: boolean; pull?: boolean };
}

export interface GitHubConfig {
  configured: boolean;
  appId: string;
  slug: string;
  installationUrl: string | null;
  webhookConfigured: boolean;
}

export type ActivityLevel = "info" | "success" | "warning" | "error";
export type ActivityCategory =
  | "analysis"
  | "github"
  | "github-webhook"
  | "ingest"
  | "chroma"
  | "system"
  | "auth";

/** A backend event shown in the live activity feed. */
export interface ActivityEvent {
  id: string;
  at: string;
  level: ActivityLevel;
  category: ActivityCategory;
  message: string;
  ownerUid?: string;
  workspaceId?: string;
  incidentId?: string;
  jobId?: string;
  details?: Record<string, unknown>;
  active?: boolean;
}

export interface Workspace {
  id: string;
  name: string;
  /** Normalised clone url, e.g. https://github.com/owner/repo.git */
  repoUrl: string;
  /** Human readable url, e.g. https://github.com/owner/repo */
  repoDisplayUrl: string;
  owner: string;
  repo: string;
  branch: string;
  defaultBranch: string | null;
  branches: string[];
  /** The CloudWatch log source of this workspace, when one is connected. */
  cloudWatch: CloudWatchConnection | null;
  /** The GitHub App installation that grants access to a private repository. */
  github?: GitHubConnection | null;
  createdAt: number;
  updatedAt: number;
}

export interface Incident {
  id: string;
  /** Pull request opened by the GitHub App, when available. */
  prUrl?: string | null;
  prNumber?: number | null;
  workspaceId: string;
  ownerUid: string;
  repoUrl: string;
  repoDisplayUrl: string;
  branch: string;
  title: string;
  errorMessage: string;
  status: IncidentStatus;
  confidence: Confidence | null;
  rootCause: string | null;
  fixPlan: string | null;
  affectedFiles: string[];
  regressionTest: RegressionTest;
  fixBranch: string | null;
  commit: string | null;
  pushed: boolean;
  severity: IncidentSeverity | string;
  source: IncidentSource | string;
  incidentId: string | null;
  priorsUsed: number;
  validationReason: string | null;
  steps: string[];
  createdAt: number;
  updatedAt: number;
}

export interface AppUser {
  uid: string;
  email: string;
  displayName: string;
}

export interface RepositorySummary {
  repoUrl: string;
  displayUrl: string;
  owner: string;
  repo: string;
  defaultBranch: string | null;
  branches: string[];
  private?: boolean;
  installationId?: number;
}

export interface AnalysisJob {
  id: string;
  workspaceId: string;
  status: "queued" | "running" | "done" | "failed";
  progress: { message: string; at: number }[];
  result: AnalysisResult | null;
  error: string | null;
  meta: Record<string, unknown>;
  createdAt: number;
  updatedAt: number;
}

export interface AnalysisResult {
  status: IncidentStatus;
  rootCause: string;
  confidence: Confidence | null;
  fixPlan: string | null;
  affectedFiles: string[];
  regressionTest: RegressionTest;
  branch: string | null;
  commit: string | null;
  push: { pushed: boolean; output?: string } | null;
  pr?: { url: string; number: number } | null;
  validation?: { validated: boolean; reason: string; steps: string[] };
  incidentId: string | null;
  priorsUsed: number;
  steps: string[];
  /** The record the API built, ready to be persisted in the Realtime Database. */
  incident?: Incident;
}

/**
 * The CloudFormation stack that connects a CloudWatch log group to
 * Codewarden.
 *
 * The API builds it for one workspace, so the ingest key of that workspace is
 * already filled in and the customer only has to create the stack.
 */
export interface CloudFormationTemplate {
  /** The stack as a JSON object, for the CloudFormation console. */
  template: Record<string, unknown>;
  /** The same stack as YAML, which is easier to read in a terminal. */
  yaml: string;
  /** The name the stack gets when the customer creates it. */
  stackName: string;
  logGroupName: string;
  filterPattern: string;
}
